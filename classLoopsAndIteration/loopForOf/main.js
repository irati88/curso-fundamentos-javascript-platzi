// -- BUCLE FOR OF -- //

// se utiliza sobre elementos de una lista, como los arrays y strings.

// Sintaxis básica:
// for (variable + of + objeto) {
// código a ejecutar
// }

let basket = ["manzana", "pera", "naranja", "uva"];

for (fruit of basket) {
  console.log(fruit); // Recorre el array de "basket" e imprime los elementos uno a uno
}